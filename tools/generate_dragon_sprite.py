"""Build the X3's 1-bit dragon sprite from the Pixelorama SVG.

Requires ImageMagick's `magick` command. This is a host-side tool only; the
firmware includes the generated header and never parses SVG or allocates an
image buffer at runtime.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "pagepet-dragon.svg"
OUTPUT = ROOT / "include" / "DragonSprite.h"
WIDTH = HEIGHT = 256


def main() -> None:
    result = subprocess.run(
        [
            "magick",
            "-background", "white",
            str(SOURCE),
            "-alpha", "remove",
            "-alpha", "off",
            "-colorspace", "gray",
            "-ordered-dither", "o8x8,2",
            "-type", "bilevel",
            "pbm:-",
        ],
        check=True,
        capture_output=True,
    )
    match = re.match(rb"P4\s+(\d+)\s+(\d+)\s", result.stdout)
    if match is None:
        raise ValueError("ImageMagick did not produce binary PBM (P4)")
    width, height = map(int, match.groups())
    if (width, height) != (WIDTH, HEIGHT):
        raise ValueError(f"Expected {WIDTH}x{HEIGHT}, got {width}x{height}")
    # PBM uses 1=black; FreeInkDisplay::drawImage uses 0=black, MSB first.
    bitmap = bytes(~value & 0xFF for value in result.stdout[match.end():])
    if len(bitmap) != WIDTH * HEIGHT // 8:
        raise ValueError(f"Expected {WIDTH * HEIGHT // 8} sprite bytes, got {len(bitmap)}")
    rows = [
        "  " + ", ".join(f"0x{value:02x}" for value in bitmap[index:index + 16]) + ","
        for index in range(0, len(bitmap), 16)
    ]
    OUTPUT.write_text(
        "// Generated by tools/generate_dragon_sprite.py from assets/pagepet-dragon.svg.\n"
        "// 256x256, 1bpp, MSB-first, 1=white. Keep source art in Git.\n"
        "#pragma once\n\n#include <Arduino.h>\n\nnamespace dragon_art {\n"
        "constexpr uint16_t kWidth = 256;\nconstexpr uint16_t kHeight = 256;\n"
        "static const uint8_t kBitmap[] PROGMEM = {\n"
        + "\n".join(rows)
        + "\n};\nstatic_assert(sizeof(kBitmap) == kWidth * kHeight / 8);\n"
        "}  // namespace dragon_art\n",
        encoding="ascii",
    )
    print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(bitmap)} sprite bytes)")


if __name__ == "__main__":
    main()
